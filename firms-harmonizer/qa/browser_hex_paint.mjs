import { chromium } from 'playwright';
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { join } from 'node:path';
const requireFrontend = createRequire(new URL('../frontend/package.json', import.meta.url));
const h3 = requireFrontend('h3-js');
const output = process.env.HEX_PAINT_OUTPUT ?? new URL('../../docs/verification/2026-11-15-hex-paint-fill/', import.meta.url).pathname;
fs.mkdirSync(output, { recursive: true });
(async () => {
    const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH ?? '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
    page.setDefaultTimeout(20000);
    const report = { checks: [], errors: [] };
    page.on('pageerror', e => report.errors.push(e.message));
    const check = (name) => { report.checks.push(name); console.log('PASS', name); };
    try {
        await page.goto(process.env.COPILOT_BROWSER_URL ?? 'http://127.0.0.1:5173');
        await page.waitForFunction(() => !document.querySelector('[aria-label="Choose dates"]')?.disabled, null, { timeout: 60000 });
        const loaded = page.waitForResponse(r => r.url().endsWith('/api/analyze') && r.request().method() === 'POST');
        await page.getByLabel('Search locations within the four approved regions').fill('40.48552565777765, -4.75540953778114');
        await page.getByLabel('Search locations within the four approved regions').press('Enter');
        assert.equal((await loaded).status(), 200);
        await page.getByLabel('Choose dates', { exact: true }).click();
        await page.getByRole('button', { name: /^2021\b/ }).click();
        await page.getByRole('button', { name: /^Aug\b/ }).click();
        await page.getByRole('button', { name: 'Continue to day', exact: true }).click();
        await page.getByRole('button', { name: /^Aug 16, 2021/ }).click();
        await page.getByRole('button', { name: 'Use this day', exact: true }).click();
        await page.waitForTimeout(800);
        await page.getByRole('button', { name: 'Select hexagons', exact: true }).click();
        await page.waitForTimeout(400);
        const box = await page.locator('[data-map-viewport]').boundingBox(), center = h3.latLngToCell(40.48552565777765, -4.75540953778114, 7), ring = h3.gridRing(center, 2);
        const pos = cell => { const [lat, lon] = h3.cellToLatLng(cell), merc = a => Math.log(Math.tan(Math.PI / 4 + a * Math.PI / 360)), scale = 512 * 2 ** 10; return [box.x + box.width / 2 + (lon + 4.75540953778114) / 360 * scale, box.y + box.height / 2 + (merc(40.48552565777765) - merc(lat)) / (2 * Math.PI) * scale]; };
        const cells = async () => (await page.locator('[aria-label="Selected hexagons"] button').allTextContents()).map(s => s.split(' ')[0]).sort();
        const fill = page.getByRole('button', { name: 'Fill', exact: true });
        assert(await fill.isDisabled());
        const far = h3.gridRing(center, 5).find(c => { const [x, y] = pos(c); return x > box.x + 450 && x < box.x + box.width - 40 && y > box.y + 200 && y < box.y + box.height - 200; });
        assert(far);
        await page.mouse.move(...pos(center));
        await page.mouse.down();
        await page.mouse.wheel(0, 200);
        await page.mouse.move(...pos(far), { steps: 1 });
        await page.waitForTimeout(100);
        await page.mouse.move(...pos(center), { steps: 1 });
        await page.mouse.up();
        await page.waitForTimeout(150);
        const fast = await cells();
        assert(fast.length > 2);
        assert(fast.includes(center) && fast.includes(far));
        for (const c of fast)
            assert(fast.length === 1 || h3.gridDisk(c, 1).some(n => n !== c && fast.includes(n)));
        check('fast held-pointer stroke interpolates intermediate cells; revisiting does not erase');
        await page.mouse.move(...pos(center));
        await page.mouse.down();
        await page.mouse.move(...pos(far), { steps: 1 });
        await page.mouse.up();
        await page.waitForTimeout(150);
        assert.deepEqual(await cells(), []);
        check('stroke beginning on selected cell erases consistently');
        await page.mouse.move(...pos(center));
        await page.mouse.down();
        await page.mouse.move(box.x + box.width + 30, box.y + box.height / 2);
        await page.mouse.up();
        await page.waitForTimeout(100);
        const released = await cells();
        await page.mouse.move(...pos(far));
        await page.waitForTimeout(100);
        assert.deepEqual(await cells(), released);
        check('pointer release outside map stops selection');
        await page.mouse.move(...pos(center));
        await page.mouse.down();
        await page.waitForTimeout(50);
        await page.evaluate(() => window.dispatchEvent(new Event('blur')));
        const blurred = await cells();
        await page.mouse.move(...pos(far), { steps: 1 });
        await page.mouse.up();
        await page.waitForTimeout(100);
        assert.deepEqual(await cells(), blurred);
        check('window blur cancels an active stroke');
        await page.getByRole('button', { name: 'Clear cells', exact: true }).click();
        await page.mouse.move(...pos(ring[0]));
        await page.mouse.down();
        for (const c of ring.slice(1, -1))
            await page.mouse.move(...pos(c), { steps: 1 });
        await page.waitForTimeout(100);
        assert(await fill.isDisabled());
        check('open perimeter cannot fill');
        await page.mouse.move(...pos(ring.at(-1)), { steps: 1 });
        await page.mouse.move(...pos(ring[0]), { steps: 1 });
        await page.mouse.up();
        await page.waitForTimeout(150);
        assert.deepEqual(await cells(), [...ring].sort());
        assert(!await fill.isDisabled());
        await page.mouse.click(...pos(ring[0]));
        await page.waitForTimeout(100);
        assert(await fill.isDisabled());
        await page.mouse.click(...pos(ring[0]));
        await page.waitForTimeout(100);
        assert(!await fill.isDisabled());
        check('single clicks still toggle cells and closing perimeter enables Fill');
        await page.mouse.move(1300, 200);
        await page.screenshot({ path: join(output, 'perimeter.png') });
        report.perimeter = await cells();
        await fill.click();
        await page.waitForTimeout(100);
        const filled = await cells(), expected = h3.gridDisk(center, 2).sort();
        assert.deepEqual(filled, expected);
        assert(await fill.isDisabled());
        report.filled = filled;
        check('Fill adds only seven enclosed cells to the twelve-cell perimeter');
        await page.screenshot({ path: join(output, 'filled.png') });
        assert.equal(await page.getByLabel('Fire AI Copilot', { exact: true }).count(), 0);
        check('painting does not open Copilot');
        const applying = page.waitForResponse(r => r.url().endsWith('/api/analyze') && r.request().method() === 'POST');
        await page.getByRole('button', { name: 'Apply hexagon area', exact: true }).click();
        const response = await applying, body = await response.json();
        report.request = response.request().postDataJSON();
        assert.equal(response.status(), 200);
        assert.equal(body.data_source, 'real');
        assert.deepEqual(h3.polygonToCells(report.request.aoi.coordinates, 7, true).sort(), expected);
        assert(body.map_hexagons.every(c => expected.includes(c.h3_index)));
        await page.getByRole('region', { name: 'Hexagon area selection' }).waitFor({ state: 'hidden' });
        assert((await page.getByLabel('Timeline selection', { exact: true }).innerText()).includes('Aug 16, 2021'));
        check('apply sends the exact filled AOI and preserves the selected day');
        await page.getByRole('button', { name: 'Fire Copilot', exact: true }).click();
        const pending = page.waitForResponse(r => r.url().endsWith('/api/explain-spike') && r.request().method() === 'POST', { timeout: 90000 });
        await page.getByLabel('Question for Fire Copilot').fill('How many detections and what total FRP in MW in this selected area?');
        await page.getByTitle('Send question', { exact: true }).click();
        const chat = await pending;
        report.chat = { request: chat.request().postDataJSON(), response: await chat.json() };
        assert.equal(chat.status(), 200);
        assert.deepEqual(report.chat.request.aoi, report.request.aoi);
        assert.deepEqual(report.chat.response.map_context.aoi, report.request.aoi);
        assert.equal(report.chat.response.map_context.period_start, '2021-08-16');
        check('Copilot uses the exact filled cells and day');
        assert.deepEqual(report.errors, []);
        report.result = 'passed';
    }
    catch (e) {
        report.result = 'failed';
        report.error = e.stack;
        console.error(e);
        await page.screenshot({ path: join(output, 'failure.png') });
        process.exitCode = 1;
    }
    finally {
        fs.writeFileSync(join(output, 'browser.json'), JSON.stringify(report, null, 2));
        await browser.close();
    }
})();
